import streamlit as st

st.set_page_config(page_title="Politique de confidentialité", page_icon="🔒")

st.title("🔒 Politique de confidentialité")
st.markdown("""
### 1. Collecte des données
L'application **Atlas - Bibliothèque Numérique SJP** collecte uniquement votre nom et prénom lors du partage d'un document. Ces informations sont utilisées dans le seul but de créditer l'auteur du document partagé.

### 2. Stockage des données
Les documents PDF partagés ainsi que les noms des contributeurs sont stockés de manière sécurisée sur le Google Drive personnel du gestionnaire de la plateforme.

### 3. Utilisation des données
Aucune donnée n'est vendue, partagée ou utilisée à des fins commerciales. Les documents sont mis à la disposition exclusive des étudiants de Saint Jérôme Polytechnique (SJP) à des fins pédagogiques.

### 4. Vos droits
Si vous souhaitez que votre nom ou un document que vous avez partagé soit retiré de la plateforme, veuillez contacter le gestionnaire de l'application.
""")